package com.mopl.global.outbox;

/**
 * 최종 실패 이벤트를 건너뛰기로 종결한 결과입니다.
 *
 * <p>{@link #ALREADY_SKIPPED} 를 실패로 두지 않습니다. 같은 요청이 두 번 들어와도 결과는
 * "그 이벤트는 건너뛴 상태다"로 같아야 합니다. 두 번째를 거절하면 응답을 못 본 운영자가
 * 자기 판단이 반영됐는지 다시 확인해야 합니다.
 *
 * <p>다만 감사 정보는 덮어쓰지 않습니다. 실제로 판단한 사람과 시각은 처음 전환한 쪽입니다.
 */
public enum OutboxSkipOutcome {

    /** 최종 실패에서 건너뛰기로 종결했습니다. */
    SKIPPED,

    /** 이미 건너뛴 이벤트입니다. 감사 정보는 처음 전환 때의 값을 그대로 둡니다. */
    ALREADY_SKIPPED,

    /** 그 eventId 를 가진 레코드가 없습니다. */
    NOT_FOUND,

    /** 레코드는 있지만 최종 실패도 건너뛰기도 아닙니다. */
    NOT_FAILED
}

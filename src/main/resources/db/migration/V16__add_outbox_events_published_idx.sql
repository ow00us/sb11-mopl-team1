-- 발행 완료 레코드 정리용 인덱스
--
-- 정리 작업이 보관 기간을 지난 발행 완료 레코드를 발행 시각이 이른 순으로 지운다.
-- 인덱스가 없으면 매 실행이 전체 테이블을 훑는데, 정리가 필요한 상황이란 곧 그 테이블이
-- 크다는 뜻이라 정리를 시작하는 시점이 가장 비싼 시점이 된다.
--
-- 부분 인덱스로 둔 이유는 정리 대상이 발행 완료 레코드뿐이기 때문이다. 발행 대기와 최종
-- 실패는 보관 기간과 무관하게 남으므로 이 인덱스에 들어갈 이유가 없다.
CREATE INDEX idx_outbox_events_published
    ON outbox_events (published_at, id)
    WHERE status = 'PUBLISHED';
